# --------------------------------------------------------- texture fitting
def _geom_repeats(geom, tile):
    """texrepeat that lays square `tile`-metre squares over a geom's face.

    MuJoCo maps a box's faces as (x,z) on the +-X and +-Y faces and (x,y) on
    the +-Z faces, so the repeats are fixed by the face's two side lengths.
    The dominant face (largest area) is the one that gets the square tile;
    thin edge strips of the same box cannot all be square at once, and are
    hidden or millimetres wide on every geom here.
    """
    type_ = geom.type
    if type_ == mujoco.mjtGeom.mjGEOM_PLANE:
        # An infinite plane has no face to fit a square to, and MuJoCo maps one
        # in WORLD units scaled by texrepeat - so for a plane the repeat IS
        # 1/tile.  (This used to fall through to the degenerate branch below
        # and return (1, 1) unconditionally, which silently made the floor's
        # _TILES entry a comment rather than a control.  Measured on the
        # overhead render: the concrete's joint grid lands ~280 px apart, i.e.
        # a ~1 m tile, exactly what repeat 1.0 gives.)
        return 1.0 / tile, 1.0 / tile
    elif type_ == mujoco.mjtGeom.mjGEOM_CYLINDER:
        # side surface: u around the circumference, v along the axis
        dims, pair = ((2.0 * np.pi * float(geom.size[0]),
                       2.0 * float(geom.size[1]))), (0, 1)
    else:
        dims = tuple(2.0 * float(s) for s in geom.size[:3])
        faces = ((0, 2), (0, 1), (1, 2))
        pair = max(faces, key=lambda p: dims[p[0]] * dims[p[1]])
    a, b = dims[pair[0]], dims[pair[1]]
    longest = max(a, b)
    if longest <= 0.0:          # degenerate geom (no face to tile)
        return 1.0, 1.0
    n = min(MAX_TILES, max(1.0, round(longest / tile)))
    return n * a / longest, max(n * b / longest, 1.0 / 256.0)


def _fit_textures(spec):
    """Give every textured geom a material whose tiles are square in metres.

    Called after paint(): geoms are already pointing at a base material, and
    each one is re-pointed at a clone carrying its own texrepeat.  Clones are
    shared between geoms of the same material and the same repeat, so the
    material count stays moderate.
    """
    cache = {}
    for g in spec.geoms:
        if g.name not in _PAINTED:
            continue
        base = _BASEMAT.get(g.material)
        if base is None:
            continue
        rx, ry = _geom_repeats(g, _TILES[g.material])
        key = (g.material, round(rx, 4), round(ry, 4))
        if key not in cache:
            m = spec.add_material()
            m.name = f"{g.material}_f{len(cache)}"
            m.textures[mujoco.mjtTextureRole.mjTEXROLE_RGB] = base.textures[
                mujoco.mjtTextureRole.mjTEXROLE_RGB]
            m.rgba = base.rgba
            m.roughness = base.roughness
            m.metallic = base.metallic
            m.shininess = base.shininess
            m.specular = base.specular
            m.reflectance = base.reflectance
            m.emission = base.emission
            m.texuniform = False
            m.texrepeat = col([rx, ry])
            cache[key] = m.name
        g.material = cache[key]
    return spec


