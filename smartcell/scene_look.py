# key light colour and the four hall fixtures (renderer reads diffuse only -
# see MAX_RENDER_LIGHTS note); values tuned by pixel-statistics sweeps
KEY_DIF = (0.90, 0.88, 0.84)
HALL_DIF = (0.75, 0.76, 0.80)


def paint(spec):
    """Assign materials to every geom by name prefix (call before compile)."""
    _PAINTED.clear()
    for g in spec.geoms:
        if not g.name:
            continue
        hit = None
        for prefix in _MATS:
            if g.name.startswith(prefix):
                hit = _MATS[prefix]
                break
        if hit is None:
            continue
        mat_name, keep = hit
        g.material = mat_name
        _PAINTED.add(g.name)
        if not keep:                    # wipe so the material colour shows
            a = float(np.asarray(g.rgba).ravel()[3])
            g.rgba = col([1.0, 1.0, 1.0, a])
    # the floor plane comes from the robot file, name "floor"
    fl = spec.geom("floor")
    fl.material = "m_floor"
    fl.rgba = col([1.0, 1.0, 1.0, 1.0])
    _PAINTED.add("floor")
    return spec


# ------------------------------------------------------------------- lights
# MuJoCo 3.14 renders at most 8 lights (measured); everything after light
# index 7 is silently ignored.  The hall contributes 4, so the studio rig is
# key + rim + the two sky washes: exactly 8, all effective.  The robot's own
# light is deleted below - it is a mjLIGHT_DIRECTIONAL, which the 3.14
# renderer ignores entirely (measured), so it only wastes a slot.
MAX_RENDER_LIGHTS = 8


def relight(spec):
    """Studio rig: shadowed key, rim, two sky domes, four hall fixtures."""
    # retire the robot's own unnamed light (directional = invisible)
    for lt in [lt for lt in spec.lights if not lt.name]:
        spec.delete(lt)

    # NOTE: the old `hall_fill` directional light was removed from
    # factory_hall.py - it compiled to intensity 0 and never lit anything.
    # Do NOT call spec.delete() on lights here: deleting an attached light
    # silently breaks every light added afterwards in MjSpec 3.14.

    # key light: high, camera side, casts the cell's shadows
    k = spec.worldbody.add_light()
    k.name = "key"
    k.pos = col([1.15, -1.85, 2.95])
    k.dir = col([-0.28, 0.36, -0.92])
    k.type = mujoco.mjtLightType.mjLIGHT_SPOT
    k.diffuse = col(list(KEY_DIF))            # slightly warm
    k.specular = col([0.22, 0.22, 0.20])
    k.castshadow = True
    k.cutoff = 50.0
    k.exponent = 18.0
    k.range = 9.0
    k.intensity = 1.0

    # NOTE: there is no separate fill light - with the 8-light cap the sky
    # dome carries the ambient wash, and it is tinted cool like north light.

    # rim/back light so the arm separates from the dark far wall
    r = spec.worldbody.add_light()
    r.name = "rim"
    r.pos = col([-0.5, 1.75, 1.55])
    r.dir = col([0.25, -0.60, -0.40])
    r.type = mujoco.mjtLightType.mjLIGHT_SPOT
    r.diffuse = col([0.30, 0.33, 0.38])
    r.specular = col([0.12, 0.13, 0.15])
    r.castshadow = False
    r.cutoff = 55.0
    r.exponent = 12.0
    r.range = 8.0
    r.intensity = 1.0

    # the four hall fixtures get their colour here.  None of them casts
    # shadows - every shadow-casting light adds a full scene re-render per
    # frame, and with 5 casters the viewer crawled at 2-3 fps.  The key light
    # alone provides the cell's contact shadows.
    for lt in spec.lights:
        if lt.name.startswith("hall_"):
            lt.diffuse = col(list(HALL_DIF))
            lt.castshadow = False

    # broad ambient dome so nothing goes black: two very wide ceiling lights
    # in opposite corners, no shadows, which between them wash the whole
    # hall including the wall tops and - measured - the roof deck.  Renderer
    # notes from measurement (MuJoCo 3.14): MjSpec lights default to
    # intensity = 0 and the renderer IGNORES light_intensity - all the work
    # is done by `diffuse`.  mjLIGHT_DIRECTIONAL contributes nothing at all,
    # and an UPWARD-pointing spot contributes nothing either (measured: the
    # picture is bit-identical with and without one), so the dome is built
    # from wide-angle spots pointing down.
    for j, (pos, dr, dif) in enumerate(((SKY1_POS, SKY1_DIR, SKY1_DIF),
                                        (SKY2_POS, SKY2_DIR, SKY2_DIF))):
        d = spec.worldbody.add_light()
        d.name = f"sky{j + 1}"
        d.type = getattr(mujoco.mjtLightType, SKY_TYPE)
        d.pos = col(pos)
        d.dir = col(dr)
        d.diffuse = col(dif)
        d.intensity = 1.0
        d.castshadow = False
        d.cutoff = SKY_CUTOFF
        d.exponent = SKY_EXP
        d.range = SKY_RANGE
    return spec


# -------------------------------------------------------------------- props
# NOTE: no free-standing props.  Anything not attached to a wall, the roof or
# a machine reads as "floating" from a viewer's free camera even when it
# physically rests on the floor - so the scene only contains objects with a
# visible carrier (pallets under crates, legs under tables, rails over stands).
def add_props(spec):
    """Reserved: set dressing that is visibly anchored.  Empty by design.

    There is no free-standing prop in this scene.  A machine base pad is not a
    prop: it is what the leg stands on (line_frame.feet).
    """
    return spec


# ------------------------------------------------------------------- polish
def polish(model):
    """Visual settings on the compiled model (quality vs speed)."""
    m = model
    # ONE shadow-casting light (the key): shadow maps are the single most
    # expensive render pass; more than one and the viewer crawls.  512 px is
    # enough for one room-scale contact shadow.
    m.vis.quality.shadowsize = 512
    # MSAA 4x on offscreen buffers doubles fill cost for little gain here
    m.vis.quality.offsamples = 0
    # planar floor reflections trigger a full extra render pass (~40 ms)
    # for a barely visible effect on a matte concrete floor: none of that
    m.mat_reflectance[:] = 0.0
    m.vis.global_.offwidth = 1920
    m.vis.global_.offheight = 1080
    # Headlight: enough that the interactive viewer is never pitch black (an
    # MjSpec-created model compiles with an all-zero headlight), but no more.
    # Measured at 0.10/0.12 it was adding a flat ~70 levels to EVERY surface -
    # enough to render the frame (albedo 160) and the anodised legs (albedo
    # 109) at the same 181/184.  The 8-light rig already lifts the darkest
    # material in the cell to 62, so nothing goes black without it.
    m.vis.headlight.ambient[:] = 0.025
    m.vis.headlight.diffuse[:] = 0.030
    m.vis.headlight.specular[:] = 0.01
    return m
