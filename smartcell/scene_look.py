"""Look and lighting for the cell: materials, lights, set dressing.

This module is deliberately the ONLY place that decides what things look like.
build_cell.py builds geometry; factory_hall.py builds the hall shell; this
module paints both and adds whatever the scene needs that has no physics role.

Everything is data-driven over geom name prefixes:  _MATS maps a prefix to a
(material, keep_rgba) pair.  Textures come from assets/tex, generated by
make_textures.py - the provenance chain stays closed, no stock photos.

Two styles:
  * material owns the colour (keep_rgba=False): the geom's rgba is wiped to
    white so the material shows pure.  Big surfaces: walls, roof, table top,
    belt, tote, bin, steel frame.
  * geom keeps its rgba as a tint (keep_rgba=True): the material is white and
    only supplies texture and finish, the geom supplies the colour.  Used
    where per-part colour carries meaning: safety-orange guards, crates,
    floor markings, cubes.

TEXTURE MAPPING (measured on this build, it is the thing that used to make the
walls look stretched):

  texuniform = false   the texture's 0..1 square lands exactly on ONE GEOM
                       FACE, and texrepeat scales it: with texrepeat (3, 2)
                       a face shows 3 x 2 repeats.  Tile size in metres is
                       therefore face_size / texrepeat.  Every material uses
                       this mode.
  texuniform = true    world-object-space coordinates: the texture's s runs
                       along the geom's local X and t along its local Y.
                       On a WALL (a box 150 mm thick) the visible face varies
                       in x and z, and z is not mapped at all - so the tiling
                       is stretched to nothing vertically.  That was the
                       "stretched wall" bug; it applies to every thin box,
                       i.e. exactly the walls and the roof slab.  Do not use
                       it for surfaces that are thin in one axis.

Because a repeat count is shared by every geom that uses the material, a
single repeat can still stretch the texture on a geom of a different shape:
the dado band is 6.2 x 1.05 m, so a (3, 1) repeat gave it 2.07 x 1.05 m tiles,
i.e. a 2:1 stretched pattern; a 6 m beam and a 3.6 m column did far worse.
So repeats are NOT stored on the material any more.  `_TILES` gives each
material a TILE SIZE IN METRES, and `_fit_textures` clones the material per
geom with `texrepeat` computed from that geom's own dominant face so the tile
is square: tile = L / round(L / _TILES[name]) with the other axis scaled by
the same factor.  There is no way left for a texture to come out stretched.

Lighting follows a studio setup anchored to the hall:
  * a warm key with shadows from the camera side lifts the robot cell,
  * a cool fill from the window band shapes the far side,
  * a rim light separates the arm from the far wall,
  * two wide sky domes wash the room so nothing goes black,
  * the four hall high-bay fixtures light the room from above.

The ceiling is the one surface no light in this rig can reach directly (a
spot's cone never gets above its own fixture), so the roof deck is a LIGHT
material with a little emission of its own - see m_roof.  Measured: the deck
renders at ~115/255 this way, where the old dark grey roof slab rendered at
about half that and read as a black ceiling.

Called from build_cell.build_spec() / build_model() - nothing else imports it.
"""
